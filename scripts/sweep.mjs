/**
 * The calibration report.
 *
 * Every daily game has one question that has to be answered before launch:
 * is the content actually solvable, and does skill change the answer? This
 * walks a year of kilns with three reference players — a careful one, a lazy
 * one, and an impatient one — and prints what each would get.
 *
 *   node scripts/sweep.mjs            # prints a table, writes proof/balance.md
 */

import { writeFileSync, mkdirSync } from 'node:fs';
import { autopilot, idleTrace, roaringTrace } from '../src/shared/sim/autopilot.ts';
import { addDays, specForDay } from '../src/shared/sim/daily.ts';
import { evaluate } from '../src/shared/sim/evaluate.ts';
import { F_MAX, F_MIN, factorAt } from '../src/shared/sim/kiln.ts';

const DAYS = Number(process.env.DAYS ?? 365);
const START = '2026-11-11';

function bestScore(ware, trace) {
  let best = 0;
  for (let x = 0; x <= 1; x += 0.01) {
    for (let y = 0; y <= 1; y += 0.01) {
      const o = evaluate({ ware, factor: factorAt(x, y), trace, flambeRoll: 1 });
      if (o.score > best) best = o.score;
    }
  }
  return best;
}

const rows = [];
for (let i = 0; i < DAYS; i++) {
  const key = addDays(START, i);
  const spec = specForDay(key);
  const careful = autopilot(spec.curve);
  const lazy = idleTrace(spec.curve);
  const impatient = roaringTrace(spec.curve);

  rows.push({
    key,
    ware: spec.ware.id,
    shape: spec.shape,
    peak: spec.peak,
    need: spec.ware.mid / spec.peak,
    careful: bestScore(spec.ware, careful.trace),
    atShelf: evaluate({ ware: spec.ware, factor: 1, trace: careful.trace, flambeRoll: 1 }).score,
    lazy: bestScore(spec.ware, lazy),
    impatient: bestScore(spec.ware, impatient),
  });
}

const sum = (pick) => rows.reduce((a, r) => a + pick(r), 0) / rows.length;
const min = (pick) => Math.min(...rows.map(pick));
const max = (pick) => Math.max(...rows.map(pick));

const lines = [];
lines.push('# KILN · calibration sweep');
lines.push('');
lines.push(`Generated by \`node scripts/sweep.mjs\` on ${new Date().toISOString().slice(0, 10)}.`);
lines.push('');
lines.push(`Days swept: **${DAYS}**, starting ${START}.`);
lines.push('');
lines.push('Three reference players, same kiln, same day:');
lines.push('');
lines.push('| player | what they do | mean | min | max |');
lines.push('| --- | --- | --- | --- | --- |');
lines.push(
  `| careful | reads 1.2s ahead, stands in the best spot | ${sum((r) => r.careful).toFixed(1)} | ${min((r) => r.careful)} | ${max((r) => r.careful)} |`,
);
lines.push(
  `| at the shelf | fires perfectly, stands in the middle | ${sum((r) => r.atShelf).toFixed(1)} | ${min((r) => r.atShelf)} | ${max((r) => r.atShelf)} |`,
);
lines.push(
  `| lazy | lights it and walks away | ${sum((r) => r.lazy).toFixed(1)} | ${min((r) => r.lazy)} | ${max((r) => r.lazy)} |`,
);
lines.push(
  `| impatient | keeps the firebox full | ${sum((r) => r.impatient).toFixed(1)} | ${min((r) => r.impatient)} | ${max((r) => r.impatient)} |`,
);
lines.push('');
const fineDays = rows.filter((r) => r.careful >= 74).length;
lines.push(
  `Days where a careful player reaches **Fine (74+)**: ${fineDays}/${DAYS}. ` +
    `Every day's ideal chamber factor stays inside the kiln (${F_MIN.toFixed(3)}–${F_MAX.toFixed(3)}): ` +
    `${rows.every((r) => r.need >= F_MIN && r.need <= F_MAX) ? 'yes' : 'NO'}.`,
);
lines.push('');
lines.push('| day | ware | schedule | peak | ideal factor | careful | at shelf | lazy | impatient |');
lines.push('| --- | --- | --- | --- | --- | --- | --- | --- | --- |');
for (const r of rows.slice(0, 30)) {
  lines.push(
    `| ${r.key} | ${r.ware} | ${r.shape} | ${r.peak.toFixed(3)} | ${r.need.toFixed(3)} | ${r.careful} | ${r.atShelf} | ${r.lazy} | ${r.impatient} |`,
  );
}
lines.push('');
lines.push(`(first 30 of ${DAYS} days shown)`);

mkdirSync('proof', { recursive: true });
writeFileSync('proof/balance.md', `${lines.join('\n')}\n`, 'utf8');

console.log(lines.slice(0, 22).join('\n'));
console.log(`\nfull table → proof/balance.md`);
if (fineDays < DAYS) {
  console.error(`\n${DAYS - fineDays} day(s) cannot reach Fine with careful play.`);
  process.exit(1);
}

/**
 * UI hygiene, measured rather than eyeballed.
 *
 *   node scripts/measure-ui.mjs
 *
 * Writes proof/ui/report.md and exits non-zero if anything is out of bounds.
 * This does not decide whether the screen is any good — only whether it is
 * physically usable on a phone.
 */

import { spawn } from 'node:child_process';
import { mkdir, writeFile } from 'node:fs/promises';
import { join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

import { chromium } from 'playwright-core';

const root = resolve(fileURLToPath(new URL('.', import.meta.url)), '..');
const PORT = 4322;
const CHROME =
  process.env.KILN_CHROME ??
  'C:/Users/张一/AppData/Local/ms-playwright/chromium-1248/chrome-win64/chrome.exe';

const server = spawn(process.execPath, [join(root, 'scripts', 'dev-server.mjs'), '--port', String(PORT), '--seed'], {
  cwd: root,
  stdio: ['ignore', 'pipe', 'pipe'],
  env: { ...process.env, KILN_NOW: '2026-11-14T09:00:00Z' },
});
const log = [];
server.stdout.on('data', (d) => log.push(String(d)));
server.stderr.on('data', (d) => log.push(String(d)));

const wait = (ms) => new Promise((r) => setTimeout(r, ms));
for (let i = 0; i < 120 && !log.join('').includes('kiln dev server'); i += 1) await wait(100);

const rows = [];
let failures = 0;

async function measure(browser, name, viewport, hashFirst, pageName = 'game') {
  const context = await browser.newContext({ viewport, deviceScaleFactor: 2 });
  const page = await context.newPage();
  await page.goto(`http://127.0.0.1:${PORT}/${pageName}.html`, { waitUntil: 'networkidle' });
  await page.waitForSelector(pageName === 'game' ? '.wares .ware' : '.card h1');
  if (hashFirst) {
    await page.locator('.wares .ware').first().click();
    const box = await page.locator('canvas').boundingBox();
    const scale = Math.min(box.width / 1000, box.height / 560);
    const dx = (box.width - 1000 * scale) / 2;
    const dy = (box.height - 560 * scale) / 2;
    await page.mouse.click(box.x + dx + 509 * scale, box.y + dy + 304 * scale);
    await page.getByRole('button', { name: /Stoke the fire/ }).click();
    await page.waitForSelector('.stoke-track');
  }

  const data = await page.evaluate(() => {
    const buttons = [...document.querySelectorAll('button')].filter((b) => b.offsetParent !== null);
    const heights = buttons.map((b) => Math.round(b.getBoundingClientRect().height));
    const widths = buttons.map((b) => Math.round(b.getBoundingClientRect().width));
    const primary = document.querySelector('.btn.primary');
    const bodyFont = Number.parseFloat(getComputedStyle(document.body).fontSize);
    const canvas = document.querySelector('canvas');
    return {
      overflowX: document.documentElement.scrollWidth - window.innerWidth,
      minButton: heights.length ? Math.min(...heights) : 0,
      primaryWidth: primary ? Math.round(primary.getBoundingClientRect().width) : -1,
      bodyFont,
      canvasHeight: canvas ? Math.round(canvas.getBoundingClientRect().height) : 0,
      viewportHeight: window.innerHeight,
    };
  });

  const checks = [
    ['no horizontal overflow', data.overflowX <= 1, `${data.overflowX}px`],
    ['every visible button is ≥ 34px tall', data.minButton >= 34, `${data.minButton}px`],
    ['primary button is wide enough to hit', data.primaryWidth < 0 ? 'n/a' : data.primaryWidth >= 110, data.primaryWidth < 0 ? 'no primary on this screen' : `${data.primaryWidth}px`],
    ['body text ≥ 13px', data.bodyFont >= 13, `${data.bodyFont}px`],
  ];
  if (pageName === 'game') {
    checks.push(['the kiln gets the room', data.canvasHeight >= data.viewportHeight * 0.5, `${data.canvasHeight}/${data.viewportHeight}px`]);
  }
  for (const [label, ok, detail] of checks) {
    const state = ok === 'n/a' ? 'n/a' : ok ? 'pass' : '**FAIL**';
    if (ok !== 'n/a' && !ok) failures += 1;
    rows.push(`| ${name} | ${label} | ${state} | ${detail} |`);
  }
  await context.close();
}

const browser = await chromium.launch({ executablePath: CHROME, args: ['--no-sandbox'] });
try {
  await measure(browser, 'desktop 1280×820', { width: 1280, height: 820 }, false);
  await measure(browser, 'desktop 1280×820 (stoking)', { width: 1280, height: 820 }, true);
  await measure(browser, 'phone 390×844', { width: 390, height: 844 }, false);
  await measure(browser, 'phone 390×844 (stoking)', { width: 390, height: 844 }, true);
  await measure(browser, 'feed card 320×320', { width: 320, height: 320 }, false, 'splash');
} finally {
  await browser.close();
  server.kill();
}

const report = `# UI measurement

Generated by \`node scripts/measure-ui.mjs\` on ${new Date().toISOString()}.
Measures hygiene only: it cannot tell whether the screen is beautiful, and it is
not used as a gate.

| viewport | check | result | measured |
| --- | --- | --- | --- |
${rows.join('\n')}

${failures === 0 ? 'All checks passed.\n' : `${failures} check(s) failed — fix before shipping.\n`}
`;

await mkdir(join(root, 'proof', 'ui'), { recursive: true });
await writeFile(join(root, 'proof', 'ui', 'report.md'), report, 'utf8');
process.stdout.write(report);
process.exit(failures === 0 ? 0 : 1);
